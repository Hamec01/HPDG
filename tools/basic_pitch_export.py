"""Basic Pitch (Spotify, Apache-2.0) -> HPDG's C++ transcriber: weights and reference outputs.

Lab only: runs from the Basic Pitch venv outside the repo (`<venv python> -I`).

usage:
  <venv python> -I tools/basic_pitch_export.py weights <out .cpp>
      the CQT kernels / low-pass filter the model builds (nnAudio CQT2010v2) and the trained
      layers (ICASSP 2022 SavedModel) as C++ arrays
  <venv python> -I tools/basic_pitch_export.py reference <audio file> <out folder>
      the file at 22.05 kHz (audio.f32), Basic Pitch's frame outputs for the whole file
      (note.f32 / onset.f32 / contour.f32, frames x bins) and its notes (notes.csv): what the C++
      port must reproduce
"""
import os
import sys

os.environ.setdefault('TF_CPP_MIN_LOG_LEVEL', '3')
import numpy as np  # noqa: E402


def cqt_layer():
    import tensorflow as tf
    from basic_pitch import models, nn  # noqa: F401
    from basic_pitch.constants import ANNOTATIONS_BASE_FREQUENCY, AUDIO_SAMPLE_RATE, CONTOURS_BINS_PER_SEMITONE, FFT_HOP
    from basic_pitch.layers import nnaudio
    n_semitones = min(int(np.ceil(12.0 * np.log2(8)) + 88), models.MAX_N_SEMITONES)
    layer = nnaudio.CQT(sr=AUDIO_SAMPLE_RATE, hop_length=FFT_HOP, fmin=ANNOTATIONS_BASE_FREQUENCY,
                        n_bins=n_semitones * CONTOURS_BINS_PER_SEMITONE, bins_per_octave=12 * CONTOURS_BINS_PER_SEMITONE)
    layer.build(tf.TensorShape([1, 43844]))
    return layer


def array(name, values):
    flat = np.asarray(values, dtype=np.float32).ravel()
    def literal(v):
        text = f'{v:.9g}'
        return text + ('f' if any(ch in text for ch in '.e') else '.0f')
    body = ',\n'.join(', '.join(literal(v) for v in flat[i:i + 8]) for i in range(0, len(flat), 8))
    return f'const float {name}[{len(flat)}] = {{\n{body}\n}};\n'


def weights(out):
    import tensorflow as tf
    from basic_pitch import ICASSP_2022_MODEL_PATH
    layer = cqt_layer()
    assert not layer.earlydownsample and layer.downsample_factor == 1.0, 'expected no early downsampling'
    basis = layer.basis  # (bins per octave, n_fft) complex
    model = tf.saved_model.load(str(ICASSP_2022_MODEL_PATH))
    var = {v.name[:-2]: v.numpy() for v in model.variables}

    parts = ['// Generated by tools/basic_pitch_export.py from Spotify Basic Pitch (ICASSP 2022 model, Apache-2.0,\n'
             '// see docs/THIRD-PARTY-NOTICES.txt). Do not edit.\n',
             '#include "BasicPitchWeights.h"\n\nnamespace bbg::basic_pitch\n{\n',
             f'// CQT2010v2: {layer.n_bins} bins, {layer.bins_per_octave} per octave, {layer.n_octaves} octaves, '
             f'kernel {layer.n_fft}, top octave from {layer.fmin_t:.6f} Hz\n',
             array('kCqtKernelReal', basis.real), array('kCqtKernelImag', basis.imag),
             array('kCqtLengths', layer.lengths), array('kLowpass', layer.lowpass_filter.numpy())]
    # keras layouts: Conv2D kernel (kh, kw, in, out) over (time, freq); BatchNormalization gamma/beta/mean/var
    for name, value in sorted(var.items()):
        parts.append(array('k_' + name.replace('/', '_').replace('-', '_'), value))
    parts.append('} // namespace bbg::basic_pitch\n')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(''.join(parts))
    print(f'{out}: {sum(v.size for v in var.values())} trained parameters, CQT {basis.shape}')
    for name, value in sorted(var.items()):
        print(f'  {name} {value.shape}')


def reference(audio_path, out):
    import librosa
    from basic_pitch import ICASSP_2022_MODEL_PATH, FilenameSuffix, build_icassp_2022_model_path
    from basic_pitch.constants import AUDIO_SAMPLE_RATE
    from basic_pitch.inference import Model, predict
    os.makedirs(out, exist_ok=True)
    audio, _ = librosa.load(audio_path, sr=AUDIO_SAMPLE_RATE, mono=True)
    audio.astype(np.float32).tofile(os.path.join(out, 'audio.f32'))
    model = Model(build_icassp_2022_model_path(FilenameSuffix.onnx))
    output, _, notes = predict(audio_path, model)
    for key in ('note', 'onset', 'contour'):
        output[key].astype(np.float32).tofile(os.path.join(out, key + '.f32'))
    with open(os.path.join(out, 'notes.csv'), 'w', encoding='utf-8') as f:
        f.write('start,end,midi,amplitude\n')
        for s, e, pitch, amp, _ in sorted(notes):
            f.write(f'{s:.6f},{e:.6f},{int(pitch)},{amp:.6f}\n')
    print(f'{audio_path}: {len(audio)} samples, {output["note"].shape[0]} frames, {len(notes)} notes '
          f'({ICASSP_2022_MODEL_PATH})')


if __name__ == '__main__':
    a = sys.argv[1:]
    if len(a) >= 2 and a[0] == 'weights':
        weights(a[1])
    elif len(a) >= 3 and a[0] == 'reference':
        reference(a[1], a[2])
    else:
        print(__doc__)
